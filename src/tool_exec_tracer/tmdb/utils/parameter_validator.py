"""
Parameter Validation Utility

Validates whether generated parameters match the expected schema,
independently of API execution success. This allows distinguishing between:
1. Parameter generation errors (wrong/missing parameters)
2. External constraint errors (correct parameters, but API fails due to permissions, state, etc.)
"""
from typing import Dict, Any, Tuple, List, Optional


def validate_parameters_schema(
    generated_params: Dict[str, Any],
    required_parameters: Dict[str, Any],
    optional_parameters: Dict[str, Any]
) -> Tuple[bool, List[str], Dict[str, Any]]:
    """
    Validate that generated parameters match the expected schema.
    
    Args:
        generated_params: Parameters generated by the LLM
        required_parameters: Expected required parameters with schema
        optional_parameters: Expected optional parameters with schema
    
    Returns:
        Tuple of (is_valid, errors, validation_details)
        - is_valid: True if parameters are valid (all required params present, no extra params)
        - errors: List of validation error messages
        - validation_details: Detailed validation information
    """
    errors = []
    validation_details = {
        "required_params_present": [],
        "required_params_missing": [],
        "optional_params_present": [],
        "unexpected_params": [],
        "type_mismatches": []
    }
    
    # Check required parameters
    for param_name, param_schema in required_parameters.items():
        if param_name in generated_params:
            validation_details["required_params_present"].append(param_name)
            # Validate type if possible
            expected_type = param_schema.get("type", "")
            actual_value = generated_params[param_name]
            type_valid, type_error = _validate_type(param_name, actual_value, expected_type)
            if not type_valid:
                validation_details["type_mismatches"].append({
                    "param": param_name,
                    "expected_type": expected_type,
                    "actual_value": actual_value,
                    "error": type_error
                })
                errors.append(type_error)
        else:
            validation_details["required_params_missing"].append(param_name)
            errors.append(f"Missing required parameter: {param_name}")
    
    # Check optional parameters (just track them, not errors)
    for param_name in optional_parameters.keys():
        if param_name in generated_params:
            validation_details["optional_params_present"].append(param_name)
    
    # Check for unexpected parameters (not in required or optional)
    # These are tracked but validation outcome depends on API result:
    # - If API succeeds: extra params are valid
    # - If API fails due to external error: extra params are still valid
    # - If API fails due to parameter error: extra params are invalid
    # This logic is handled in evaluate_parameter_generation_quality()
    all_expected_params = set(required_parameters.keys()) | set(optional_parameters.keys())
    for param_name in generated_params.keys():
        if param_name not in all_expected_params:
            validation_details["unexpected_params"].append(param_name)
            # Don't add to errors here - will be determined by API result
    
    # Schema validation passes if:
    # 1. All required parameters are present
    # 2. No type mismatches
    # Note: Extra/unexpected parameters don't fail schema validation
    # Final validation considers API success and error type (see evaluate_parameter_generation_quality)
    is_valid = (
        len(validation_details["required_params_missing"]) == 0 and
        len(validation_details["type_mismatches"]) == 0
    )
    if not is_valid:
        print(f"Validation details: {validation_details}")
        print(f"Errors: {errors}")
    
    return is_valid, errors, validation_details


def _validate_type(param_name: str, value: Any, expected_type: str) -> Tuple[bool, Optional[str]]:
    """
    Validate parameter type.
    
    Returns:
        Tuple of (is_valid, error_message)
    """
    if not expected_type:
        # No type constraint specified
        return True, None
    
    # Handle None/null values
    if value is None or value == "":
        # Empty values might be acceptable for optional params
        # This is checked at the required param level
        return True, None
    
    # Normalize type names
    type_map = {
        "string": str,
        "str": str,
        "integer": int,
        "int": int,
        "number": (int, float),
        "float": float,
        "boolean": bool,
        "bool": bool,
        "array": list,
        "list": list,
        "object": dict,
        "dict": dict
    }
    
    expected_type_lower = expected_type.lower()
    expected_python_type = type_map.get(expected_type_lower)
    
    if expected_python_type is None:
        # Unknown type, can't validate
        return True, None
    
    # Check type
    if not isinstance(value, expected_python_type):
        return False, f"Parameter '{param_name}' has wrong type: expected {expected_type}, got {type(value).__name__}"
    
    return True, None


def categorize_api_error(
    error_message: str,
    api_response: Dict[str, Any]
) -> Tuple[str, str]:
    """
    Categorize API error to determine if it's a parameter issue or external constraint.
    
    Args:
        error_message: The error message string
        api_response: The full API response dict
    
    Returns:
        Tuple of (category, reason)
        Categories:
        - PARAMETER_ERROR: Missing, invalid, or malformed parameters, wrong parameter values (404)
        - EXTERNAL_CONSTRAINT: Permissions, account state (403)
        - RATE_LIMIT: Rate limiting
        - SERVER_ERROR: Server-side issues
        - NETWORK_ERROR: Connection/timeout issues
        - UNKNOWN: Unclassified error
        
    Note on HTTP 404 errors:
        These are treated as PARAMETER_ERROR because:
        - In REST APIs, 404 usually means wrong parameter value (e.g., wrong ID in URL path)
        - If parameter was correct, the resource would be found
        - This is stricter but more accurate for parameter validation
    """
    if not error_message:
        return "UNKNOWN", "No error message provided"
    
    error_lower = error_message.lower()
    
    # Check HTTP status codes first for more reliable classification
    # HTTP 400 - Bad Request (usually parameter errors)
    if "http 400" in error_lower or "bad request" in error_lower:
        # HTTP 400 is almost always a parameter error
        return "PARAMETER_ERROR", error_message
    
    # HTTP 401 - Unauthorized (external constraint)
    if "http 401" in error_lower or "unauthorized" in error_lower:
        return "EXTERNAL_CONSTRAINT", error_message
    
    # HTTP 403 - Forbidden (external constraint)
    if "http 403" in error_lower or "forbidden" in error_lower:
        return "EXTERNAL_CONSTRAINT", error_message
    
    # HTTP 404 - Not Found (treat as parameter error)
    # In REST APIs, 404 usually means wrong parameter value (especially IDs in URL)
    if "http 404" in error_lower or ("not found" in error_lower and "404" in error_lower):
        return "PARAMETER_ERROR", error_message
    
    # HTTP 429 - Rate Limit
    if "http 429" in error_lower or "rate limit" in error_lower or "too many requests" in error_lower or "quota" in error_lower:
        return "RATE_LIMIT", error_message
    
    # HTTP 5xx - Server errors
    if any(code in error_lower for code in ["http 500", "http 502", "http 503", "http 504"]) or \
       "internal server error" in error_lower or "service unavailable" in error_lower or "server error" in error_lower:
        return "SERVER_ERROR", error_message
    
    # Network errors (timeouts, connections)
    if any(keyword in error_lower for keyword in ["timeout", "connection", "network", "unreachable"]):
        return "NETWORK_ERROR", error_message
    
    # Now check more specific parameter error keywords (for non-HTTP errors)
    if any(keyword in error_lower for keyword in [
        "missing required", "required parameter", "invalid parameter",
        "malformed", "validation error", "invalid input", "parameter error"
    ]):
        return "PARAMETER_ERROR", error_message
    
    # External constraint keywords (for non-HTTP errors)
    if any(keyword in error_lower for keyword in [
        "permission", "access denied", "restriction violated",
        "not allowed", "premium", "subscription",
        "does not exist", "no active", "no player", "not available"
    ]):
        return "EXTERNAL_CONSTRAINT", error_message
    
    # Generic "not found" without HTTP status (probably external)
    if "not found" in error_lower:
        return "EXTERNAL_CONSTRAINT", error_message
    
    # Generic "invalid" or "missing" without more context - harder to classify
    # Default to UNKNOWN to be conservative
    if "invalid" in error_lower or "missing" in error_lower:
        return "UNKNOWN", f"Ambiguous error (contains 'invalid'/'missing' without clear HTTP status): {error_message}"
    
    return "UNKNOWN", error_message


def evaluate_parameter_generation_quality(
    generated_params: Dict[str, Any],
    required_parameters: Dict[str, Any],
    optional_parameters: Dict[str, Any],
    api_success: bool,
    api_error_message: str,
    api_response: Dict[str, Any]
) -> Dict[str, Any]:
    """
    Comprehensive evaluation of parameter generation quality.
    
    This separates parameter generation correctness from API execution success,
    providing independent metrics for each aspect.
    
    Args:
        generated_params: Parameters generated by the LLM
        required_parameters: Expected required parameters
        optional_parameters: Expected optional parameters
        api_success: Whether the API call succeeded
        api_error_message: Error message if API failed
        api_response: Full API response
    
    Returns:
        Dict with evaluation results:
        - params_valid: bool - whether parameters are valid (schema + not LLM's fault)
        - parameter_validation_errors: list - validation errors
        - parameter_validation_details: dict - detailed validation info
        - api_error_category: str - category of API error (for analysis)
        - api_error_reason: str - reason for API error
        
        Note: api_success is NOT included here as it's already in the top-level log
        
        Validation Logic (Simplified):
        - params_valid is True if:
          1. API succeeded → parameters are valid (API accepted them)
          2. API failed with RATE_LIMIT, NETWORK_ERROR → benefit of doubt
          3. API failed with EXTERNAL_CONSTRAINT (403) → check schema
          4. API failed with SERVER_ERROR (5xx) → check schema
        - params_valid is False if:
          1. API failed with PARAMETER_ERROR (400, 404) → parameters are invalid (LLM's fault)
          2. API failed with EXTERNAL_CONSTRAINT (403) AND schema invalid
          3. API failed with SERVER_ERROR (5xx) AND schema invalid
        
        This ensures: parameter_validation_rate >= api_success_rate
    """
    # Validate parameters against schema (only used for ambiguous cases)
    params_valid, validation_errors, validation_details = validate_parameters_schema(
        generated_params, required_parameters, optional_parameters
    )
    
    # Categorize API error (if any)
    if not api_success:
        error_category, error_reason = categorize_api_error(api_error_message, api_response)
        print(f"Error category: {error_category}, Error reason: {error_reason}")
    else:
        error_category = "NONE"
        error_reason = ""
    
    # Simplified validation logic:
    if api_success:
        # Case 1: API succeeded - parameters are VALID
        params_valid = True
        validation_errors = []
        # Clear validation_details since API accepted the parameters
        validation_details = {
            "required_params_present": list(validation_details.get("required_params_present", [])),
            "required_params_missing": [],
            "optional_params_present": list(validation_details.get("optional_params_present", [])),
            "unexpected_params": [],
            "type_mismatches": []
        }
    elif error_category == "PARAMETER_ERROR":
        # Case 2: API rejected parameters (400, 404) - INVALID
        params_valid = False
        if "API returned PARAMETER_ERROR" not in validation_errors:
            validation_errors = ["API returned PARAMETER_ERROR - parameters were rejected by the API"]
    elif error_category == "EXTERNAL_CONSTRAINT":
        # Case 3: External constraint (403) - use schema check
        # Keep params_valid from schema validation
        if not params_valid:
            validation_errors.append(f"API failed with external constraint AND schema validation failed")
    elif error_category == "SERVER_ERROR":
        # Case 4a: Server error (5xx) - use schema check
        # Could be server bug OR bad parameter value that crashed the server
        # Keep params_valid from schema validation
        if not params_valid:
            validation_errors.append(f"API failed with server error AND schema validation failed")
    else:
        # Case 4b: Other errors (RATE_LIMIT, NETWORK_ERROR, UNKNOWN)
        # Give benefit of doubt - assume parameters were correct
        params_valid = True
        validation_errors = []
        # Clear validation_details since we're giving benefit of doubt
        validation_details = {
            "required_params_present": list(validation_details.get("required_params_present", [])),
            "required_params_missing": [],
            "optional_params_present": list(validation_details.get("optional_params_present", [])),
            "unexpected_params": [],
            "type_mismatches": []
        }

    if not params_valid:
        print(f"Validation errors: {validation_errors}")
    
    return {
        "params_valid": params_valid,
        "parameter_validation_errors": validation_errors,
        "parameter_validation_details": validation_details,
        "api_error_category": error_category,
        "api_error_reason": error_reason
    }


